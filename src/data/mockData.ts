const genEngagement = (base: number, variance: number) =>
  Array.from({ length: 30 }, (_, i) => {
    const date = new Date(2026, 3, 15)
    date.setDate(date.getDate() + i)
    return {
      date: date.toLocaleDateString('en-IN', { month: 'short', day: 'numeric' }),
      likes: Math.round(base + Math.sin(i * 0.4) * variance + Math.random() * variance * 0.5),
      comments: Math.round((base / 8) + Math.sin(i * 0.3) * (variance / 8) + Math.random() * 5),
      shares: Math.round((base / 3) + Math.cos(i * 0.5) * (variance / 4) + Math.random() * 8),
      reach: Math.round(base * 4.2 + Math.sin(i * 0.2) * variance * 3),
    }
  })

